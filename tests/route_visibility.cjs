const assert=require('node:assert/strict');
const {routeVisibility:check,visibilityGrid}=require('../web/route_visibility.js');
const run=paths=>check(paths,300,300,{rectangleFraction:1});
assert.ok(run([[[0,50],[300,50]]]).passes,'long crossing');
assert.ok(run([[[0,50],[230,50]]]).passes,'terminates inside third cell');
assert.ok(run([[[20,50],[150,50],[150,150]]]).passes,'sharp turn');
assert.equal(run([[[99,99],[101,101],[99,101],[101,99]]]).count,0,'corner grazes');
assert.equal(run([[[0,50],[90,50]],[[110,50],[190,50]],[[210,50],[290,50]]]).passes,false,'disconnected paths do not pool');
assert.equal(run([[[0,100],[300,100]]]).count,3,'grid boundary not counted twice');
assert.equal(run([[[0,50],[300,50]],[[0,50],[300,50]]]).count,3,'duplicate directions independent');
assert.equal(run([[[0,50],[114,50]]]).count,1,'minimum length');
assert.equal(run([[[0,50],[115,50]]]).count,2,'threshold inclusive');
assert.equal(run([[[400,50],[700,50]]]).passes,false,'pan away');
assert.ok(run([[[0,50],[300,50]]]).passes);
assert.equal(check([[[0,50],[300,50]]],3000,3000).passes,false,'zoom out');
assert.throws(()=>visibilityGrid(300,300,{gridSize:0}));
console.log('Coverage: crossings, internal termini, turns, corner grazes, disconnected parts, boundaries, duplicate directions, pan/zoom and config passed');

const {contextualHits}=require('../web/route_visibility.js');
const routes=[{id:'a',paths:[[[0,0],[100,0]]]},{id:'b',paths:[[[0,5],[100,5]]]},{id:'disconnected',paths:[[[0,50],[10,50]],[[90,50],[100,50]]]}];
const hits=contextualHits(routes,[50,2],p=>p);
assert.deepEqual(hits.map(h=>h.route.id),['a','b'],'overlapping routes both selectable');
assert.deepEqual(hits[0].origin,{x:50,y:0},'anchor interpolates along line');
assert.equal(contextualHits(routes,[50,50],p=>p).length,0,'no imaginary joining segments');
assert.equal(contextualHits([routes[0]],[50,16],p=>p).length,0,'desktop tolerance');
assert.equal(contextualHits([routes[0]],[50,16],p=>p,18).length,1,'touch tolerance');
assert.deepEqual(contextualHits([routes[0]],[100,0],p=>[p[0]*2,p[1]*2])[0].origin,{x:50,y:0},'screen-space projection retains world anchor');
console.log('Contextual hit testing passed');

const {coverageEmphasis}=require('../web/route_visibility.js');
const partial=coverageEmphasis(run([[[0,50],[114,50]]]));
const slightlyMore=coverageEmphasis(run([[[0,50],[114.5,50]]]));
const full=coverageEmphasis(run([[[0,50],[300,50],[300,150],[0,150],[0,250],[300,250]]]));
assert.ok(slightlyMore.opacity>partial.opacity,'partial-cell traversal changes emphasis continuously');
assert.ok(full.opacity>partial.opacity&&full.width>partial.width,'greater coverage has stronger emphasis');
assert.ok(full.opacity<=.7&&full.width<4,'context remains softer than the active route');
assert.ok(coverageEmphasis(null).opacity>=.4,'secondary context remains identifiable');
console.log('Coverage-only visual emphasis: continuous, bounded and independent of eligibility passed');
